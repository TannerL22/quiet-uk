"""Write notes/CURRENT_GENERATIONS.md: which artifacts/ folders are in use.

Read-only. Classifies every generation folder as in use (by the app launcher or
the road calculation), an input of one in use, an older version of a newer
generation, temporary, or otherwise unreferenced. Nothing is moved or deleted.
"""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / 'artifacts'
NOTE = ROOT / 'notes/CURRENT_GENERATIONS.md'
# Releases scripts/29_serve_explorer.py and launch_quiet_uk.ps1 open, in preference order.
APP = ['england_map_v1', 'england_map_preview', 'oxford_london_map_v1', 'tiled_map_v2', 'source_regions_v2', 'source_regions_v1', 'source_pilot_v1',
       'recorded_sound_v3', 'explorer_display_v4']
CALCULATIONS = ['real_road_reflection_calculation_v5', 'real_road_reflection_calculation_v4']
VERSION = re.compile(r'^(?P<stem>.+)_v(?P<version>\d+)$')


def read(path):
    try:
        return json.loads(Path(path).read_bytes())
    except (OSError, ValueError):
        return None


def main():
    folders = sorted(p for p in ARTIFACTS.iterdir() if p.is_dir() and not p.name.startswith(('.', '_')))
    names = {p.name for p in folders}
    loose = sorted(p.name for p in ARTIFACTS.iterdir() if p.is_file())
    roles = {}
    for name in APP:
        if name in names:
            roles.setdefault(name, 'app release')
            acquisition = (read(ARTIFACTS / name / 'manifest.json') or {}).get('acquisition', {}).get('path')
            if acquisition and Path(acquisition).name in names:
                roles.setdefault(Path(acquisition).name, f'input of {name}')
    inputs = {}
    sealed_calculation = next((n for n in CALCULATIONS if (ARTIFACTS / n / 'inventory.json').exists()), None)
    for name in CALCULATIONS:
        protocol = read(ARTIFACTS / name / 'protocol.json')
        if protocol:
            if (ARTIFACTS / name / 'inventory.json').exists():
                state = ' (sealed)'
            elif sealed_calculation:
                state = f' (stopped; superseded by {sealed_calculation})'
            else:
                state = ' (in progress)'
            roles[name] = 'road calculation' + state
            for parent in protocol.get('parent_inventory_sha256', {}):
                inputs.setdefault(parent, name)
    newest = {}
    for name in names:
        match = VERSION.match(name)
        if match:
            stem, version = match['stem'], int(match['version'])
            newest[stem] = max(newest.get(stem, 0), version)
    rows = []
    for folder in folders:
        name = folder.name
        # An England-style acquisition keeps the provider catalogue in inventory.json; its seal is manifest.json.
        acquisition = (folder / 'plan.json').exists() and (folder / 'records').is_dir()
        sealed = (folder / ('manifest.json' if acquisition else 'inventory.json')).exists()
        match = VERSION.match(name)
        if name in roles:
            role = roles[name]
        elif name in inputs:
            role = f'input of {inputs[name]}'
        elif 'tmp' in name.split('_'):
            role = 'temporary'
        elif match and int(match['version']) < newest[match['stem']]:
            role = f"older than {match['stem']}_v{newest[match['stem']]}"
        else:
            role = 'unreferenced'
        rows.append((name, role, 'sealed' if sealed else 'unsealed'))
    order = ['app', 'road', 'input', 'unreferenced', 'older', 'temporary']
    rows.sort(key=lambda r: (next(i for i, k in enumerate(order) if r[1].startswith(k)), r[0]))
    counts = {}
    for _, role, _ in rows:
        key = role.split(' ')[0]
        counts[key] = counts.get(key, 0) + 1
    lines = ['# Current artifact generations', '',
             'Generated by `python scripts/list_generations.py` from the folders present in `artifacts/`.',
             'Re-run it after adding or archiving generations. It reads only; nothing is moved or deleted.', '',
             '- **app release**: opened by the explorer launcher (first present map release wins).',
             '- **road calculation / input of …**: the road calculation and the sealed generations its protocol pins.',
             '- **older than …**: superseded by a newer version; kept for verification and rollback.',
             '- **temporary**: scratch output of earlier checks; a candidate to archive once confirmed unused.',
             '- **unreferenced**: not used by the app or the current calculation; history or supporting evidence.', '',
             'Summary: ' + ', '.join(f'{v} {k}' for k, v in sorted(counts.items())) + f', plus {len(loose)} loose files.', '',
             '| Folder | Role | State |', '|---|---|---|']
    lines += [f'| `{n}` | {r} | {s} |' for n, r, s in rows]
    lines += ['', f'Loose files at the top of `artifacts/` ({len(loose)}): logs, benchmarks and receipts from earlier work.', '']
    NOTE.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'Wrote {NOTE.relative_to(ROOT)}: ' + ', '.join(f'{v} {k}' for k, v in sorted(counts.items())))


if __name__ == '__main__':
    main()

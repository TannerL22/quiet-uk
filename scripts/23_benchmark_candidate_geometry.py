def _independent_labels(mask: np.ndarray) -> np.ndarray:
    mask = np.asarray(mask, dtype=bool)
    labels = np.zeros(mask.shape, dtype=np.int32)
    label = 0
    for row in range(mask.shape[0]):
        for col in range(mask.shape[1]):
            if not mask[row, col] or labels[row, col]:
                continue
            label += 1
            labels[row, col] = label
            queue = deque([(row, col)])
            while queue:
                current_row, current_col = queue.popleft()
                for next_row, next_col in (
                    (current_row - 1, current_col),
                    (current_row + 1, current_col),
                    (current_row, current_col - 1),
                    (current_row, current_col + 1),
                ):
                    if (
                        0 <= next_row < mask.shape[0]
                        and 0 <= next_col < mask.shape[1]
                        and mask[next_row, next_col]
                        and labels[next_row, next_col] == 0
                    ):
                        labels[next_row, next_col] = label
                        queue.append((next_row, next_col))
    return labels


def _synthetic_masks() -> dict[str, np.ndarray]:
    contiguous = np.ones((64, 64), dtype=bool)
    isolated = np.zeros((80, 80), dtype=bool)
    isolated[::2, ::2] = True
    small = np.zeros((80, 80), dtype=bool)
    for row in range(0, 80, 3):
        for col in range(0, 80, 3):
            small[row : row + 2, col : col + 2] = True
    topology = np.zeros((80, 80), dtype=bool)
    topology[5:35, 5:35] = True
    topology[15:25, 15:25] = False
    topology[5:35, 45:75] = True
    topology[15:25, 55:65] = False
    topology[20, 35:46] = True
    return {
        "contiguous_64": contiguous,
        "isolated_single_cells_80": isolated,
        "small_four_cell_components_80": small,
        "holes_and_narrow_connection_80": topology,
    }


def _optimized_with_metrics(
    labels: np.ndarray,
    retained_labels: set[int],
    *,
    repeats: int = 1,
) -> tuple[dict[int, dict[str, Any]], dict[str, Any]]:
    original = candidates_module.shapes
    metrics = {"polygonization_calls": 0, "raster_cells_supplied": 0}

    def counted(*args: Any, **kwargs: Any):
        metrics["polygonization_calls"] += 1
        metrics["raster_cells_supplied"] += int(np.asarray(args[0]).size)
        return original(*args, **kwargs)

    candidates_module.shapes = counted
    try:
        elapsed_runs = []
        run_metrics = []
        geometries = {}
        for _ in range(repeats):
            calls_before = metrics["polygonization_calls"]
            cells_before = metrics["raster_cells_supplied"]
            started = time.perf_counter()
            geometries = candidates_module._polygonize_labelled_region(labels, retained_labels, TRANSFORM)
            elapsed_runs.append(time.perf_counter() - started)
            run_metrics.append({
                "polygonization_calls": metrics["polygonization_calls"] - calls_before,
                "raster_cells_supplied": metrics["raster_cells_supplied"] - cells_before,
            })
    finally:
        candidates_module.shapes = original
    metrics.update(run_metrics[0])
    metrics["elapsed_seconds"] = sorted(elapsed_runs)[len(elapsed_runs) // 2]
    metrics["elapsed_seconds_runs"] = elapsed_runs
    metrics["measurement_repeats"] = repeats
    metrics["per_run_metrics_consistent"] = len(set((item["polygonization_calls"], item["raster_cells_supplied"]) for item in run_metrics)) == 1
    return geometries, metrics


def _rasterized_geometry(geometry: dict[str, Any], shape: tuple[int, int]) -> np.ndarray:
    bng_geometry = transform_geom("EPSG:4326", "EPSG:27700", geometry, precision=12)
    return rasterize(
        [(bng_geometry, 1)],
        out_shape=shape,
        transform=TRANSFORM,
        fill=0,
        all_touched=False,
        dtype="uint8",
    ).astype(bool)


def _verify_geometry_membership(
    labels: np.ndarray,
    retained_labels: set[int],
    geometries: dict[int, dict[str, Any]],
) -> dict[str, Any]:
    union = np.zeros(labels.shape, dtype=bool)
    per_label = {}
    valid = 0
    holes = 0
    for label in sorted(retained_labels):
        geometry = geometries[label]
        shapely_geometry = shapely_shape(geometry)
        valid += int(shapely_geometry.is_valid)
        if geometry["type"] == "Polygon":
            holes += len(shapely_geometry.interiors)
        else:
            holes += sum(len(part.interiors) for part in shapely_geometry.geoms)
        rasterized = _rasterized_geometry(geometry, labels.shape)
        expected = labels == label
        per_label[str(label)] = bool(np.array_equal(rasterized, expected))
        if np.any(union & rasterized):
            per_label[str(label)] = False
        union |= rasterized
    failed_labels = [label for label, exact in per_label.items() if not exact]
    return {
        "all_geometries_valid": valid == len(retained_labels),
        "valid_geometry_count": valid,
        "hole_count": holes,
        "per_label_membership_exact": not failed_labels,
        "per_label_checked_count": len(per_label),
        "per_label_failed_labels": failed_labels,
        "union_membership_exact": bool(np.array_equal(union, np.isin(labels, list(retained_labels)))),
        "nonoverlapping_footprints": bool(np.sum(union) == sum(np.sum(labels == label) for label in retained_labels)),
    }


def _measure_case(name: str, mask: np.ndarray) -> dict[str, Any]:
    labels = _independent_labels(mask)
    retained_labels = set(range(1, int(labels.max()) + 1))
    geometries, metrics = _optimized_with_metrics(labels, retained_labels, repeats=3)
    correctness = _verify_geometry_membership(labels, retained_labels, geometries)
    baseline = BASELINE_CASES[name]
    optimized = {
        "region_shape": list(mask.shape),
        "component_count": int(labels.max()),
        "eligible_cells": int(mask.sum()),
        **metrics,
        "correctness": correctness,
    }
    optimized["speedup_vs_baseline"] = baseline["elapsed_seconds_median"] / metrics["elapsed_seconds"]
    return {"baseline": baseline, "optimized": optimized}


def _measure_maximum_fragmented() -> dict[str, Any]:
    mask = np.zeros((400, 400), dtype=bool)
    mask[::2, ::2] = True
    labels = np.zeros(mask.shape, dtype=np.int32)
    labels[::2, ::2] = np.arange(1, int(mask.sum()) + 1, dtype=np.int32).reshape(200, 200)
    geometries, metrics = _optimized_with_metrics(labels, set(range(1, int(mask.sum()) + 1)))
    return {
        "region_shape": [400, 400],
        "requested_cells": 160000,
        "component_count": int(mask.sum()),
        **metrics,
        "returned_geometry_count": len(geometries),
        "all_labels_returned": len(geometries) == int(mask.sum()),
    }


def _pilot_comparison() -> dict[str, Any]:
    v1_json = json.loads((ROOT / "artifacts/candidate_screening_pilot_v1/candidates.json").read_text(encoding="utf-8"))
    v1_geojson = json.loads((ROOT / "artifacts/candidate_screening_pilot_v1/candidates.geojson").read_text(encoding="utf-8"))
    original = candidates_module.shapes
    metrics = {"polygonization_calls": 0, "raster_cells_supplied": 0, "polygonization_elapsed_seconds": 0.0}

    def counted(*args: Any, **kwargs: Any):
        metrics["polygonization_calls"] += 1
        metrics["raster_cells_supplied"] += int(np.asarray(args[0]).size)
        started = time.perf_counter()
        try:
            return original(*args, **kwargs)
        finally:
            metrics["polygonization_elapsed_seconds"] += time.perf_counter() - started

    candidates_module.shapes = counted
    try:
        started = time.perf_counter()
        screening = candidates_module.screen_candidates(
            ROOT / "artifacts/england_catalogue_v3",
            ROOT / "data/processed/england/tiles",
            ROOT / "data/processed/england_mask/england_100m_mask.tif",
            PILOT_BBOX,
            45,
            10,
        )
        metrics["screening_elapsed_seconds"] = time.perf_counter() - started
    finally:
        candidates_module.shapes = original

    current = screening.report
    clean_current = candidates_module._publication_payload(current)
    v1_components = {item["component_id"]: item for item in v1_json["components"]}
    current_components = {item["component_id"]: item for item in clean_current["components"]}
    v1_features = {feature["properties"]["component_id"]: feature for feature in v1_geojson["features"]}
    current_features = {feature["properties"]["component_id"]: feature for feature in screening.geojson["features"]}
    membership_differences = 0
    valid_geometry_count = 0
    with rasterio.open(ROOT / "data/processed/england_mask/england_100m_mask.tif") as mask:
        # The pilot geometry is compared on its exact requested 200 x 200 grid.
        pilot_transform = Affine(100, 0, PILOT_BBOX[0], 0, -100, PILOT_BBOX[3])
    for component_id in sorted(current_features):
        current_geometry = current_features[component_id]["geometry"]
        v1_geometry = v1_features[component_id]["geometry"]
        valid_geometry_count += int(shapely_shape(current_geometry).is_valid)
        if not np.array_equal(
            _rasterized_geometry_on_transform(current_geometry, (200, 200), pilot_transform),
            _rasterized_geometry_on_transform(v1_geometry, (200, 200), pilot_transform),
        ):
            membership_differences += 1
    return {
        "baseline": {
            "component_count": 128,
            "retained_component_cells": 17305,
            **BASELINE_PILOT,
        },
        "optimized": {
            "component_count": current["summary"]["retained_component_count"],
            "retained_component_cells": current["summary"]["retained_component_cells"],
            **metrics,
            "valid_geometry_count": valid_geometry_count,
        },
        "equivalence": {
            "run_parameters_match": current["parameters"] == v1_json["parameters"],
            "catalogue_build_id_match": current["catalogue"]["build_id"] == v1_json["catalogue"]["build_id"],
            "component_ids_and_order_match": [item["component_id"] for item in clean_current["components"]] == [item["component_id"] for item in v1_json["components"]],
            "component_summaries_match": current["summary"] == v1_json["summary"] and all(current_components[key] == v1_components[key] for key in current_components),
            "airport_partitions_match": all(current_components[key]["airport"] == v1_components[key]["airport"] for key in current_components),
            "geometry_membership_difference_count": membership_differences,
            "all_geometries_valid": valid_geometry_count == len(current_features),
        },
    }


def _rasterized_geometry_on_transform(geometry: dict[str, Any], shape: tuple[int, int], transform: Affine) -> np.ndarray:
    bng_geometry = transform_geom("EPSG:4326", "EPSG:27700", geometry, precision=12)
    return rasterize(
        [(bng_geometry, 1)], out_shape=shape, transform=transform, fill=0, all_touched=False, dtype="uint8"
    ).astype(bool)


def _markdown(record: dict[str, Any]) -> str:
    lines = [
        "# Candidate geometry verification",
        "",
        "This is a bounded evidence record for the single-pass polygonization change; it is not a general benchmark suite.",
        "",
        "## Environment",
        "",
        f"- Python: `{record['environment']['python']}`; platform: `{record['environment']['platform']}`",
        f"- Rasterio/GDAL/PROJ: `{record['environment']['rasterio']}` / `{record['environment']['gdal']}` / `{record['environment']['proj']}`",
        "",
        "## Synthetic cases",
        "",
        "| Case | Grid | Components | Baseline calls / cells | Optimized calls / cells | Baseline s | Optimized s | Speedup |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, result in record["synthetic_cases"].items():
        baseline = result["baseline"]
        optimized = result["optimized"]
        lines.append(
            f"| {name} | {optimized['region_shape'][0]}×{optimized['region_shape'][1]} | {optimized['component_count']} | "
            f"{baseline['polygonization_calls']} / {baseline['raster_cells_supplied']:,} | "
            f"{optimized['polygonization_calls']} / {optimized['raster_cells_supplied']:,} | "
            f"{baseline['elapsed_seconds_median']:.6f} | {optimized['elapsed_seconds']:.6f} | {optimized['speedup_vs_baseline']:.2f}× |"
        )
    maximum = record["maximum_fragmented_case"]
    lines.extend([
        "",
        f"Maximum request: `{maximum['region_shape'][0]}×{maximum['region_shape'][1]}` ({maximum['requested_cells']:,} cells), "
        f"`{maximum['component_count']:,}` isolated components, one polygonization call, "
        f"`{maximum['raster_cells_supplied']:,}` cells supplied, `{maximum['elapsed_seconds']:.6f}` seconds, "
        f"and `{maximum['returned_geometry_count']:,}` geometries returned.",
        "",
        "## Pilot comparison",
        "",
        f"The preserved v1 pilot was compared with the optimized run: `{record['pilot_comparison']['equivalence']['geometry_membership_difference_count']}` geometry-membership differences, "
        f"`{record['pilot_comparison']['optimized']['valid_geometry_count']}` valid geometries, and identical component IDs/order, summaries, airport partitions, parameters, and catalogue build ID.",
        "",
        "The measured improvement removes repeated regional raster polygonization. One feature per component, coordinate transformation, and JSON serialization still scale with component count and output complexity. Timings are environment-specific and are not universal performance guarantees.",
    ])
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Benchmark and verify candidate geometry generation")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "artifacts/candidate_geometry_verification_v1",
        help="New output directory for the evidence record",
    )
    args = parser.parse_args(argv)
    output = args.output_dir.resolve()
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise SystemExit(f"Output must be a new or empty directory: {output}")

    synthetic = {name: _measure_case(name, mask) for name, mask in _synthetic_masks().items()}
    record = {
        "record_type": "candidate_geometry_verification",
        "record_schema_version": 1,
        "generated_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "environment": {
            "python": platform.python_version(),
            "platform": platform.platform(),
            "rasterio": rasterio.__version__,
            "gdal": rasterio.__gdal_version__,
            "proj": rasterio.__proj_version__,
        },
        "synthetic_cases": synthetic,
        "maximum_fragmented_case": _measure_maximum_fragmented(),
        "pilot_comparison": _pilot_comparison(),
        "baseline_method": "Pre-change full regional component_mask polygonization, measured before the single-pass change.",
        "optimized_method": "One rasterio.features.shapes pass over integer component labels, masked to retained labels, grouped by label.",
    }
    output.mkdir(parents=True, exist_ok=True)
    (output / "geometry_verification.json").write_text(
        json.dumps(record, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (output / "geometry_verification.md").write_text(_markdown(record), encoding="utf-8")
    print(json.dumps({
        "output_dir": str(output),
        "pilot_geometry_membership_differences": record["pilot_comparison"]["equivalence"]["geometry_membership_difference_count"],
        "maximum_components": record["maximum_fragmented_case"]["component_count"],
    }, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
